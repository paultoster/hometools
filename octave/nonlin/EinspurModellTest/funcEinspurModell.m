function ee = funcEinspurModell(x)

  global p
  
  p.CyFA   = x(1);
  p.CyRA   = x(2);
  p.JzFzg  = x(3);
     
  p.a11   = -(p.CyFA+p.CyRA)/p.mFzg;
  p.a12   = (p.CyRA*p.lrFzg-p.CyFA*p.lfFzg)/p.mFzg;
  p.a21   = (p.CyRA*p.lrFzg-p.CyFA*p.lfFzg)/p.JzFzg;
  p.a22   = -(p.CyRA*p.lrFzg*p.lrFzg+p.CyFA*p.lfFzg*p.lfFzg)/p.JzFzg;
  p.b1    = p.CyFA/p.mFzg/p.isteer;
  p.b2    = p.CyFA*p.lfFzg/p.JzFzg/p.isteer;
  
  p.yawVeh0  = 0.0;
  p.yawpVeh0 = 0.0;
  p.betaVeh0 = 0.0;
  
  ee  = 0.0;
  for iliste = 1:p.nmessfile_liste
    
    % Messwerte
    [okay,d] = d_data_read_mat(p.messfile_liste{iliste});
    
    n     = length(d.time);
    
%     Tspan = [d.time(1) d.time(n)]; % Solve from t=1 to t=5
%     IC = [0.0,d.yawpVeh(1)]; % y(t=0) = 1
%     mdl_name = 'simulink_Einspurmodell_COG_linear';
% %     load_system(mdl_name)
% %     set_param([mdl_name,'/table_deltaStWhl'], 'InputValues','[1,2,3,4,5]')
% %     close_system(mdl_name,1)
%     tic
%     sim(mdl_name,Tspan);
%     wandel_vektor_in_struct
% %     Y = [res.yawpVeh,res.yawpVeh];
% %     T = res.time;
% %     [T Y] = ode45(@(t,y) einspurmodell_COG_linear(t,y,p,d),Tspan,IC); % Solve ODE
%     toc
    
    tic
    % Parameterstruktur
    %==================
    par = struct([]);
    par = ds_set_par(par ...
                    ,'group','control' ...
                    ,'name','delta_t' ...
                    ,'val',p.delta_t ...
                    ,'unit','s' ...
                    ,'com','Abtastzeit Simulation' ...
                    );
    par = ds_set_par(par ...
                    ,'group','control' ...
                    ,'name','delta_t_out' ...
                    ,'val',p.delta_t_out ...
                    ,'unit','s' ...
                    ,'com','Ausgabeschrittweite Simulation' ...
                    );
    par = ds_set_par(par ...
                    ,'group','control' ...
                    ,'name','t_start' ...
                    ,'val',d.time(1) ...
                    ,'unit','s' ...
                    ,'com','Startzeit Simulation' ...
                    );
    par = ds_set_par(par ...
                    ,'group','control' ...
                    ,'name','t_end' ...
                    ,'val', d.time(n) ...
                    ,'unit','s' ...
                    ,'com','Endzeit Simulation' ...
                    );


    group = 'fzg_einspur';

    par = ds_set_par_single(par,   p.a11,    'A11',      group, '-', 'velocity independend part Systemmatrix');
    par = ds_set_par_single(par,   p.a12,    'A12',      group, '-', 'velocity independend part Systemmatrix');
    par = ds_set_par_single(par,   p.a21,    'A21',      group, '-', 'velocity independend part Systemmatrix');
    par = ds_set_par_single(par,   p.a22,    'A22',      group, '-', 'velocity independend part Systemmatrix');

    par = ds_set_par_single(par,   p.b1,     'B1',       group, '-', 'velocity independend part Inputmatrix');
    par = ds_set_par_single(par,   p.b2,     'B2',       group, '-', 'velocity independend part Inputmatrix');


    par = ds_set_par_single(par,   0.0,     'yawpVeh0',  group, 'rad/s', 'starting yawRate for integration');
    par = ds_set_par_single(par,   0.0,     'yawVeh0',   group, 'rad',   'starting yawAngle for integration');
    par = ds_set_par_single(par,   0.0,     'betaVeh0',  group, 'rad',   'starting slidingAngle for integration');
                  
    par = ds_set_par(par ...
                    ,'group','Input' ...
                    ,'name','vVehTab' ...
                    ,'xname','time' ...
                    ,'xunit','s' ...
                    ,'xvec',d.time ...
                    ,'xcom','Zeitvektor' ...
                    ,'yname','vVeh' ...
                    ,'yunit','m/s' ...
                    ,'yvec',d.vVeh ...
                    ,'ycom','vVeh' ...
                    );
    par = ds_set_par(par ...
                    ,'group','Input' ...
                    ,'name','deltaStWhlTab' ...
                    ,'xname','time' ...
                    ,'xunit','s' ...
                    ,'xvec',d.time ...
                    ,'xcom','Zeitvektor' ...
                    ,'yname','deltaStWhl' ...
                    ,'yunit','rad' ...
                    ,'yvec',d.deltaStWhl ...
                    ,'ycom','deltaStWhl' ...
                    );
    try
     res  = mexEinspurmodell(par);
     flag = 1;
      if( sum(isnan(res.yawpVeh)) )
        e = 1e30;
      elseif(flag)
        yawp_sim = interp1(res.time,res.yawpVeh,d.time,'linear','extrap');
        delta = d.yawpVeh - yawp_sim;

        % figure,plot(d.time,d.yawpVeh,'k-',res2.time,res2.yawpVeh,'g-',res.time,res.yawpVeh,'r-'),grid on
        e  = sqrt((delta'*delta));
      end
    catch ME
     getReport(ME)
     e    = 1e30;
     flag = 0;
    end
    
    toc

    % Fehler gesamt
    ee = ee+e*p.gewichtung(iliste);
  end
  ee = ee/p.nmessfile_liste;
  if( isinf(ee) ),ee=1e31;end
  % fprintf('ee  = %f\n\n',ee);
end
